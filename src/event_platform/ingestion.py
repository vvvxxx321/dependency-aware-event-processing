"""Pure domain logic for ingestion. No AWS calls here."""
from __future__ import annotations

import hashlib
import json
import math
import uuid
import time
from dataclasses import dataclass
from typing import Any, Protocol
from urllib.parse import quote


MAX_CONSUMERS = 99  # identity + one write per consumer <= 100 txn items


class InvalidEvent(ValueError):
    """Invalid source event schema or duplicate JSON properties."""


class EventConflict(ValueError):
    """One event identity was reused with different immutable source content."""


def _unique_pairs(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result = {}
    for key, value in pairs:
        if key in result:
            raise InvalidEvent(f"duplicate JSON key: {key}")
        result[key] = value
    return result


def _reject_nonfinite(value: Any) -> Any:
    if isinstance(value, float) and not math.isfinite(value):
        raise InvalidEvent("NaN and Infinity not allowed")
    if isinstance(value, dict):
        return {k: _reject_nonfinite(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_reject_nonfinite(v) for v in value]
    return value


@dataclass(frozen=True)
class SourceEvent:
    event_id: str
    producer_id: str
    action: str
    timestamp_ms: int
    parameters: dict[str, Any]
    entity_id: str | None
    original: dict[str, Any]

    @classmethod
    def from_json(cls, body: str) -> "SourceEvent":
        try:
            payload = json.loads(body, object_pairs_hook=_unique_pairs,
                                 parse_constant=lambda _: (_ for _ in ()).throw(
                                     InvalidEvent("non-finite numeric constant")))
        except (ValueError, TypeError) as exc:
            raise InvalidEvent(str(exc)) from exc
        if not isinstance(payload, dict):
            raise InvalidEvent("source message must be a JSON object")
        allowed = {"EventId", "ProducerId", "Action", "Timestamp", "Parameters", "EntityId"}
        unknown = set(payload) - allowed
        if unknown:
            raise InvalidEvent(f"unknown source fields: {sorted(unknown)}")
        for required in ("EventId", "ProducerId", "Action"):
            if not isinstance(payload.get(required), str) or not payload[required].strip():
                raise InvalidEvent(f"{required} must be a nonblank string")
        try:
            parsed_event_id = uuid.UUID(payload["EventId"])
        except (ValueError, AttributeError) as exc:
            raise InvalidEvent("EventId must be a canonical UUID v4 generated by the producer") from exc
        if parsed_event_id.version != 4 or str(parsed_event_id) != payload["EventId"]:
            raise InvalidEvent("EventId must be a lowercase canonical UUID v4")
        t = payload.get("Timestamp")
        if type(t) is not int or t < 0 or t >= 10**13:
            raise InvalidEvent("Timestamp must be epoch milliseconds, 0 <= t < 10^13")
        params = payload.get("Parameters")
        if not isinstance(params, dict):
            raise InvalidEvent("Parameters must be a JSON object")
        if any(not isinstance(k, str) for k in params):
            raise InvalidEvent("Parameters keys must be strings")
        entity_id = payload.get("EntityId")
        if entity_id is not None and (not isinstance(entity_id, str) or not entity_id):
            raise InvalidEvent("EntityId, when supplied, must be a nonblank string")
        _reject_nonfinite(payload)
        return cls(payload["EventId"], payload["ProducerId"], payload["Action"],
                   t, params, entity_id, payload)

    def fingerprint(self) -> str:
        canonical = json.dumps(self.original, ensure_ascii=False, sort_keys=True,
                               separators=(",", ":"), allow_nan=False)
        return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def escape_segment(value: str) -> str:
    """Unambiguously separate composite-key fields that might include '#'."""
    return quote(value, safe="")


def route_key(producer_id: str, action: str) -> str:
    return f"{escape_segment(producer_id)}#{escape_segment(action)}"


def event_identity_key(event: SourceEvent) -> dict[str, str]:
    return {"ProducerId": event.producer_id, "SK": f"EVENT#{escape_segment(event.event_id)}"}


def task_sort_key(event: SourceEvent, consumer_id: str) -> str:
    return (f"{escape_segment(event.action)}#{escape_segment(consumer_id)}#"
            f"{event.timestamp_ms:013d}#{escape_segment(event.event_id)}")


def task_id(event: SourceEvent, consumer_id: str) -> str:
    raw = "\x00".join((event.producer_id, event.event_id, consumer_id))
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


def records_for(event: SourceEvent, consumers: list[str], *, now_ms: int | None = None,
                rules: dict[str, list[dict[str, Any]]] | None = None) -> list[dict[str, Any]]:
    """Identity + one PENDING task per consumer. `rules` maps ConsumerId -> rule snapshots that gate it."""
    if len(consumers) > MAX_CONSUMERS:
        raise InvalidEvent(f"maximum {MAX_CONSUMERS} consumers in one atomic ingress transaction")
    if len(consumers) != len(set(consumers)) or any(not c or not isinstance(c, str) for c in consumers):
        raise InvalidEvent("ConsumerIds must be unique nonempty strings")
    ingested_at = now_ms if now_ms is not None else int(time.time() * 1000)
    payload = dict(event.original)
    identity = {
        **event_identity_key(event), "RecordType": "EVENT", "EventId": event.event_id,
        "Action": event.action, "Timestamp": event.timestamp_ms,
        "Payload": payload, "PayloadFingerprint": event.fingerprint(),
        "ConsumerIds": sorted(consumers), "IngestedAt": ingested_at,
        "RoutingStatus": "ROUTED" if consumers else "NO_SUBSCRIBERS",
    }
    tasks = [{
        "ProducerId": event.producer_id, "SK": task_sort_key(event, c),
        "RecordType": "TASK", "TaskId": task_id(event, c),
        "EventId": event.event_id, "Action": event.action,
        "Parameters": dict(event.parameters), "Timestamp": event.timestamp_ms,
        "ConsumerId": c, "Status": "PENDING", "StatusUpdatedOn": ingested_at,
        "IngestedAt": ingested_at, "Rules": list((rules or {}).get(c, [])),
        # Resolver (DynamoDB Streams INSERT) owns the PENDING -> READY transition.
    } for c in sorted(consumers)]
    return [identity, *tasks]


class IngestStore(Protocol):
    def consumers_for(self, producer_id: str, action: str) -> list[str]: ...
    def rules_for(self, consumer_id: str, client_action: str) -> list[dict[str, Any]]: ...
    def atomically_ingest(self, event: SourceEvent, records: list[dict[str, Any]]) -> str: ...


def ingest(body: str, store: IngestStore) -> str:
    event = SourceEvent.from_json(body)
    consumers = store.consumers_for(event.producer_id, event.action)
    rules = {c: store.rules_for(c, event.action) for c in consumers}
    records = records_for(event, consumers, rules=rules)
    return store.atomically_ingest(event, records)
